// Global Language Manager
let currentLang = localStorage.getItem('derma_lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('derma_lang', lang);
  
  const html = document.documentElement;
  html.setAttribute('lang', lang);
  html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  
  // Apply text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Update Language Switcher UI
  const langText = document.getElementById('lang-switch-text');
  if (langText) {
    langText.innerText = lang === 'en' ? 'عربي' : 'English';
  }
  
  // Dispatch custom event for dynamic scripts
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'ar' : 'en';
  setLanguage(nextLang);
}

// Initial setup on load
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
